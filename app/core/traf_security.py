def main():
    import argparse
    
    parser = argparse.ArgumentParser(
        description="Traffic Analysis File Security Tool",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Generate a license key
  python traf_security.py generate-key --customer "Acme Corp" --days 365
  
  # Encrypt a .traf file
  python traf_security.py encrypt data.traf data.etraf --key TRAF-A1B2-C3D4-E5F6
  
  # Decrypt (for testing)
  python traf_security.py decrypt data.etraf data_decrypted.traf --key TRAF-A1B2-C3D4-E5F6
  
  # Show file info
  python traf_security.py info data.etraf
  
  # Get machine ID (for machine-locked licenses)
  python traf_security.py machine-id
        """)
    
    sub = parser.add_subparsers(dest='command')
    
    # generate-key
    gen = sub.add_parser('generate-key', help='Generate a license key')
    gen.add_argument('--customer', required=True, help='Customer name')
    gen.add_argument('--days', type=int, default=365, help='Validity in days')
    gen.add_argument('--machine-lock', action='store_true', help='Lock to current machine')
    
    # encrypt
    enc = sub.add_parser('encrypt', help='Encrypt .traf → .etraf')
    enc.add_argument('input', help='Input .traf file')
    enc.add_argument('output', help='Output .etraf file')
    enc.add_argument('--key', required=True, help='License key')
    enc.add_argument('--customer', help='Customer name')
    enc.add_argument('--expiry', help='Expiry date (YYYY-MM-DD)')
    enc.add_argument('--machine-id', help='Lock to machine ID')
    
    # decrypt
    dec = sub.add_parser('decrypt', help='Decrypt .etraf → .traf')
    dec.add_argument('input', help='Input .etraf file')
    dec.add_argument('output', help='Output .traf file')
    dec.add_argument('--key', required=True, help='License key')
    
    # info
    inf = sub.add_parser('info', help='Show .etraf file info')
    inf.add_argument('input', help='.etraf file')
    
    # machine-id
    sub.add_parser('machine-id', help='Show current machine ID')
    
    args = parser.parse_args()
    
    if args.command == 'generate-key':
        machine_id = get_machine_id() if args.machine_lock else None
        license_info = generate_customer_license(
            args.customer, args.days, machine_id=machine_id)
        print(f"License Key:  {license_info['license_key']}")
        print(f"Customer:     {license_info['customer_name']}")
        print(f"Issued:       {license_info['issued_date']}")
        print(f"Expires:      {license_info['expiry_date'] or 'Never'}")
        if machine_id:
            print(f"Machine ID:   {machine_id}")
        print(f"\nStore this key securely — it cannot be recovered!")
    
    elif args.command == 'encrypt':
        expiry = None
        if args.expiry:
            expiry = datetime.strptime(args.expiry, '%Y-%m-%d').isoformat()
        encrypt_traf(args.input, args.output, args.key,
                     customer_name=args.customer, expiry_date=expiry,
                     machine_id=args.machine_id)
        print(f"Encrypted: {args.input} → {args.output}")
    
    elif args.command == 'decrypt':
        decrypt_traf(args.input, args.key, args.output)
        print(f"Decrypted: {args.input} → {args.output}")
    
    elif args.command == 'info':
        header = read_etraf_header(args.input)
        print(f"=== .etraf File Info ===")
        print(f"Format version: {header.get('version')}")
        print(f"Created:        {header.get('created')}")
        print(f"Customer:       {header.get('customer', 'N/A')}")
        print(f"Expiry:         {header.get('expiry', 'None')}")
        print(f"Machine locked: {header.get('machine_lock', False)}")
        print(f"Original size:  {header.get('original_size', 0) / 1024:.1f} KB")
    
    elif args.command == 'machine-id':
        print(f"Machine ID: {get_machine_id()}")
    
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
